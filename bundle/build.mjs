// Builds site-bundle.js: the custom site-footer scripts in one file, in footer order.
// Each line of manifest.txt is "<commit> <file>": the exact version the live footer loaded
// from jsDelivr. Run from the repo root: node bundle/build.mjs
//
// Files that are only IIFEs get a try/catch, so one failing script can't stop the rest
// (separate <script> tags gave that for free). Files with top-level functions or
// variables stay unwrapped, because other scripts call them as globals.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const WRAP = new Set([
  "lenis-init.js", "cursor-trail.js", "work-filter.js", "text-roll.js", "view-more.js",
  "snippets-scroll.js", "video-player.js", "card-reveal.js", "mvp-emblem.js",
  "mouse-slider.js", "launch-modal.js", "halftone-portrait.js", "head-tilt.js",
  "about-stats.js", "backflip.js", "contact-panel.js", "menu.js",
]);

const entries = readFileSync(new URL("manifest.txt", import.meta.url), "utf8")
  .trim().split("\n").map((l) => l.trim().split(/\s+/));

let out = "/* site-bundle.js: generated by bundle/build.mjs, do not edit by hand */\n";
for (const [sha, file] of entries) {
  const src = execFileSync("git", ["show", `${sha}:${file}`], { encoding: "utf8" });
  out += `\n/* ===== ${file} @ ${sha.slice(0, 7)} ===== */\n`;
  out += WRAP.has(file)
    ? `try {\n${src}\n;} catch (e) { console.error("[site-bundle] ${file}", e); }\n`
    : `${src}\n;\n`;
}
writeFileSync("site-bundle.js", out);
console.log(`site-bundle.js: ${entries.length} files, ${out.length} bytes`);
